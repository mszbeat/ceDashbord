-- CE Dashboard — اسکیمای v2 (کاهش حجم + تجمیع سمت دیتابیس)
--
-- اصول:
--  * هیچ نام کلیدی در هر ردیف تکرار نمی‌شود؛ نام‌ها فقط در `indicator_registry` هستند.
--  * flags → یک ستون `bigint` بیت‌ماسک (تا ۶۳ شاخص در هر بانک).
--  * metrics/counters → ستون‌های typed با نام واقعی (double precision / bigint / integer).
--  * cats/paths/services/rotbe → کد `smallint` با جدول دیکشنری.
--  * display_extras (ستون ~۱٫۳–۱٫۸ کیلوبایتی) حذف؛ فقط «جزئیات نمایشی لازم» در `sample_detail` نگه داشته می‌شود.
--  * ایندکس‌ها: PK(day, request_id) + (request_id) + (day, ts, request_id). بدون GIN.
--  * پارتیشن ماهانه روی `day`.
--
-- محرمانگی (همان سیاست v1): nationalCode، متن آزاد پیام خام، نام شعبه و گزارش خام ذخیره نمی‌شود.
-- فقط متن «قالبی» پیام در `message_dict` (با شناسهٔ عددی) نگه داشته می‌شود.

-- ─────────────────────────── registry ───────────────────────────
CREATE TABLE IF NOT EXISTS indicator_registry (
  bank            text    NOT NULL,
  kind            text    NOT NULL,      -- flag|cat|path|service|counter|metric|rotbe
  code            smallint NOT NULL,     -- برای flag: شمارهٔ بیت؛ بقیه: شناسهٔ عددی (>=1)
  id              text    NOT NULL,      -- شناسهٔ پایدار (کلید قبلی در JSON)
  label           text,
  topic           text,
  meta            jsonb   NOT NULL DEFAULT '{}'::jsonb,
  active          boolean NOT NULL DEFAULT true,
  PRIMARY KEY (bank, kind, code)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_indicator_registry_id ON indicator_registry(bank, kind, id);

-- ─────────────────────── پیام‌ها (بدون دادهٔ خام) ───────────────────────
CREATE TABLE IF NOT EXISTS message_dict (
  code         smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_key  text NOT NULL UNIQUE,
  label        text NOT NULL,
  topic        text NOT NULL,
  message_text text
);

