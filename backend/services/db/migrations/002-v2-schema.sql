-- ─────────── دیکشنری مقادیر کم‌تنوع (model/status/error/message/amountKind/service) ───────────
-- در v1 این رشته‌ها در هر ردیف تکرار می‌شدند؛ اینجا هر مقدار یک‌بار کد smallint می‌گیرد.
CREATE TABLE IF NOT EXISTS value_dict (
  bank   text     NOT NULL,
  kind   text     NOT NULL,   -- model|status|error|message|amountKind|service
  value  text     NOT NULL,
  code   smallint NOT NULL,
  PRIMARY KEY (bank, kind, value),
  UNIQUE (bank, kind, code)
);

-- نگاشت شناسهٔ خارجی ← UUID (فقط برای شناسه‌هایی که UUID معتبر نبودند)
CREATE TABLE IF NOT EXISTS external_id_map (
  external_id text PRIMARY KEY,
  request_id  uuid NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_external_id_map_request ON external_id_map(request_id);

-- ─────────── پیکربندی لیست‌ها (title و ترتیب ردیف‌های گزارش) ───────────
CREATE TABLE IF NOT EXISTS list_specs (
  bank  text     NOT NULL,
  index smallint NOT NULL,
  title text     NOT NULL,
  meta  jsonb    NOT NULL DEFAULT '{}'::jsonb,
  PRIMARY KEY (bank, index)
);

-- ────────────────── جزئیات نمایشی اسپارس (فقط ردیف‌های قابل بررسی) ──────────────────
-- برای هر (روز، شاخص) حداکثر `row_cap` ردیف اول نگه داشته می‌شود؛ سقف نمایش HTML هم ۱۰۰ است.
CREATE TABLE IF NOT EXISTS sample_detail (
  bank        text    NOT NULL,
  day         date    NOT NULL,
  request_id  uuid    NOT NULL,
  flag_bits   bigint  NOT NULL DEFAULT 0,   -- همان بیت‌ماسک ردیف
  rank_value  double precision,
  cat_extra   jsonb,                        -- فقط مقادیر نمایشی cats که واقعاً بررسی می‌شوند
  list_extra  jsonb,                        -- فقط برای listهای منطبق
  flag_extra  jsonb,                        -- فقط برای flagهای true که row دارند
  rank_extra  jsonb,                        -- sortValue هر flag (فقط وقتی مقدار دارد)
  credit_extra jsonb,                       -- ردیف‌های نمایشی هشدار اعتباری
  credit_value jsonb,                       -- مقدار کامل credit_alerts (فقط وقتی هشدار هست)
  summary_extra jsonb,                      -- ستون‌های نمایندگی هر بانک (مثل «احتمال نکول») — بازسازی base از داده
  PRIMARY KEY (bank, day, request_id)
);
CREATE INDEX IF NOT EXISTS idx_sample_detail_flag_cover ON sample_detail(bank, day) INCLUDE (flag_bits, request_id);

-- ─────────────────────────── day_runs ───────────────────────────
CREATE TABLE IF NOT EXISTS day_runs (
  bank                text    NOT NULL,
  day                 date    NOT NULL,
  mode                text    NOT NULL DEFAULT 'nightly',
  status              text    NOT NULL DEFAULT 'pending',
  source_total        integer,
  distinct_stored     integer,          -- COUNT(DISTINCT request_id) بعد از اجرا (C1/C2)
  checkpoint          integer NOT NULL DEFAULT 0,
  ingested_count      integer NOT NULL DEFAULT 0,
  success_count       integer NOT NULL DEFAULT 0,
  fail_count          integer NOT NULL DEFAULT 0,
  skipped_other_method integer NOT NULL DEFAULT 0,
  error_count         integer NOT NULL DEFAULT 0,
  analysis_version    text,
  started_at          timestamptz,
  finished_at         timestamptz,
  error               text,
  updated_at          timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (bank, day)
);

-- ─────────────────────── rollup روزانه (فاز ۳) ───────────────────────
CREATE TABLE IF NOT EXISTS day_rollup (
  bank             text    NOT NULL,
  day              date    NOT NULL,
  analysis_version text    NOT NULL,
  rows             integer NOT NULL,
  success          integer NOT NULL,
  fail             integer NOT NULL,
  stats            jsonb   NOT NULL,    -- شمارش flag/cat/path/service/counter + آمار متریک‌ها (بدون آرایهٔ خام)
  built_at         timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (bank, day, analysis_version)
);

-- ─────────────────────────── جداول مدیریتی ───────────────────────────
CREATE TABLE IF NOT EXISTS sample_access_logs (
  id            bigserial PRIMARY KEY,
  request_id    uuid NOT NULL,
  accessed_at   timestamptz NOT NULL DEFAULT now(),
  actor         text,
  roles         jsonb NOT NULL DEFAULT '[]'::jsonb,
  ip            text,
  user_agent    text
);
CREATE INDEX IF NOT EXISTS idx_sample_access_logs_request ON sample_access_logs(request_id, accessed_at DESC);

CREATE TABLE IF NOT EXISTS cron_configs (
  id                 text PRIMARY KEY DEFAULT 'nightly_default',
  enabled            boolean NOT NULL DEFAULT false,
  schedule_mode      text NOT NULL DEFAULT 'daily',
  hour               integer NOT NULL DEFAULT 2 CHECK (hour >= 0 AND hour <= 23),
  minute             integer NOT NULL DEFAULT 0 CHECK (minute >= 0 AND minute <= 59),
  cron_expr          text NOT NULL DEFAULT '0 2 * * *',
  timezone           text NOT NULL DEFAULT 'Asia/Tehran',
  banks              text[] NOT NULL DEFAULT ARRAY['tavan_mellat','tavan_resalat','tavan_postbank']::text[],
  target_offset_days integer NOT NULL DEFAULT 1 CHECK (target_offset_days >= 0 AND target_offset_days <= 30),
  rebuild            boolean NOT NULL DEFAULT false,
  last_slot          text,
  last_run_at        timestamptz,
  last_status        text,
  last_error         text,
  last_summary       jsonb,
  updated_at         timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS auth_refresh_tokens (
  id               bigserial PRIMARY KEY,
  token_hash       text NOT NULL UNIQUE,
  family_id        text NOT NULL,
  username         text NOT NULL,
  roles            jsonb NOT NULL DEFAULT '["visitor"]'::jsonb,
  remember_me      boolean NOT NULL DEFAULT false,
  expires_at       timestamptz NOT NULL,
  rotated_at       timestamptz,
  revoked_at       timestamptz,
  replaced_by_hash text,
  ip               text,
  user_agent       text,
  created_at       timestamptz NOT NULL DEFAULT now(),
  last_used_at     timestamptz
);
CREATE INDEX IF NOT EXISTS idx_auth_refresh_tokens_username ON auth_refresh_tokens(username);
CREATE INDEX IF NOT EXISTS idx_auth_refresh_tokens_family ON auth_refresh_tokens(family_id);
CREATE INDEX IF NOT EXISTS idx_auth_refresh_tokens_expires ON auth_refresh_tokens(expires_at);

CREATE TABLE IF NOT EXISTS backend_action_logs (
  id          bigserial PRIMARY KEY,
  occurred_at timestamptz NOT NULL DEFAULT now(),
  level       text NOT NULL,
  category    text NOT NULL,
  action      text NOT NULL,
  actor       text,
  roles       jsonb NOT NULL DEFAULT '[]'::jsonb,
  method      text,
  path        text,
  status_code integer,
  duration_ms integer,
  request_id  text,
  ip          text,
  user_agent  text,
  error_code  text,
  message     text,
  meta        jsonb NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX IF NOT EXISTS idx_backend_action_logs_occurred ON backend_action_logs(occurred_at DESC);
CREATE INDEX IF NOT EXISTS idx_backend_action_logs_action ON backend_action_logs(action, occurred_at DESC);
CREATE INDEX IF NOT EXISTS idx_backend_action_logs_level ON backend_action_logs(level, occurred_at DESC);
CREATE INDEX IF NOT EXISTS idx_backend_action_logs_actor ON backend_action_logs(actor, occurred_at DESC);

CREATE TABLE IF NOT EXISTS admin_jobs (
  id          text PRIMARY KEY,
  source      text NOT NULL,
  status      text NOT NULL,
  created_at  timestamptz NOT NULL,
  finished_at timestamptz,
  payload     jsonb NOT NULL,
  updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_admin_jobs_created_at ON admin_jobs(created_at DESC);

-- وضعیت اعمال migrationهای این فایل (برای اجرای idempotent)
CREATE TABLE IF NOT EXISTS schema_migrations (
  version    text PRIMARY KEY,
  applied_at timestamptz NOT NULL DEFAULT now()
);

-- جدول نسخه‌های تحلیل (قبل از جداول نمونه‌ها لازم است)
CREATE TABLE IF NOT EXISTS analysis_versions (
  code    smallint PRIMARY KEY,
  version text NOT NULL UNIQUE
);

-- جدول دیکشنری کدهای cats (bank, cat_code) → value_code → text
CREATE TABLE IF NOT EXISTS cat_dict (
  bank       text     NOT NULL,
  cat_code   smallint NOT NULL,
  value_code smallint NOT NULL,
  value      text     NOT NULL,
  PRIMARY KEY (bank, cat_code, value_code)
);

-- ────────────── ساخت جداول نمونهٔ بانک‌ها (بدون LIKE INCLUDING ALL) ──────────────
-- ستون‌های typed متریک/کانتر از رجیستری ساخته می‌شوند؛ برای هر بانک فقط ستون‌های خودش.
-- اجرا از طریق `services/db/schema-v2-builder.js` انجام می‌شود تا هم در Node و هم در
-- ابزار migration قابل استفاده باشد (DDL داینامیک است).
